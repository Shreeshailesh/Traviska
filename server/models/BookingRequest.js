const mongoose = require("mongoose");

const bookingRequestSchema = new mongoose.Schema(
  {
    requestCode: {
      type: String,
      required: true,
      unique: true,
      index: true,
    },
    bookingId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Booking",
      required: true,
      index: true,
    },
    bookingCode: { type: String, default: "" },
    customerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
      index: true,
    },
    customerSnapshot: {
      name: { type: String, default: "" },
      email: { type: String, default: "" },
      phone: { type: String, default: "" },
    },
    tripTitle: { type: String, default: "" },
    requestType: {
      type: String,
      enum: [
        "CustomerCancel",
        "CustomerReschedule",
        "CompanyRescheduleProposal",
        "ManualRefundAction",
      ],
      required: true,
      index: true,
    },
    status: {
      type: String,
      enum: [
        "Pending Review",
        "Awaiting Customer Response",
        "Approved",
        "Rejected",
        "Completed",
      ],
      default: "Pending Review",
      index: true,
    },
    reason: { type: String, default: "" },
    customerExplanation: { type: String, default: "" },
    internalNotes: { type: String, default: "" },
    oldSlotId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "TripSlot",
      default: null,
    },
    oldDate: { type: String, default: "" },
    proposedSlotId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "TripSlot",
      default: null,
    },
    proposedDate: { type: String, default: "" },
    responseDeadline: { type: Date, default: null },
    travellers: { type: Number, default: 1 },
    rescheduleFee: { type: Number, default: 0 },
    priceDifference: { type: Number, default: 0 },
    eligibleRefundAmount: { type: Number, default: 0 },
    refundPercentage: { type: Number, default: 0 },
    amountPaidRupees: { type: Number, default: 0 },
    cancellationFeeRupees: { type: Number, default: 0 },
    cancellationSource: { type: String, enum: ["", "Customer", "Traviska"], default: "" },
    originalPaymentMethod: { type: String, default: "" },
    gatewayTransactionRef: { type: String, default: "" },
    policyVersion: { type: String, default: "2026-11-v1" },
    refundState: {
      type: String,
      enum: [
        "Not Applicable",
        "Pending Admin Approval",
        "Approved — Pending Initiation",
        "Initiation In Progress",
        "Initiated",
        "Processing",
        "Completed",
        "Failed — Requires Action",
        "Reconciliation Required",
      ],
      default: "Not Applicable",
      index: true,
    },
    refundApprovedBy: { type: String, default: "" },
    refundApprovedAt: { type: Date, default: null },
    gatewayRefundId: { type: String, default: "" },
    gatewayRefundResponse: { type: mongoose.Schema.Types.Mixed, default: null },
    flaggedForInvestigation: { type: Boolean, default: false },
    investigationNote: { type: String, default: "" },
    customerDecision: {
      type: String,
      enum: ["None", "Accept New Date", "Request 100% Refund"],
      default: "None",
    },
    decisionAt: { type: Date, default: null },
    assignedAdmin: { type: String, default: "" },
    reviewedBy: { type: String, default: "" },
    reviewedAt: { type: Date, default: null },
    isReadByAdmin: { type: Boolean, default: false, index: true },
    idempotencyKey: {
      type: String,
      unique: true,
      sparse: true,
    },
    auditHistory: [
      {
        action: { type: String, required: true },
        actor: { type: String, default: "System" },
        note: { type: String, default: "" },
        at: { type: Date, default: Date.now },
      },
    ],
  },
  { timestamps: true }
);

module.exports = mongoose.model("BookingRequest", bookingRequestSchema);
